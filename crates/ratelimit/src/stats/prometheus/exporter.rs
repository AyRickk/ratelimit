//! What upstream's Prometheus sink does with each flushed stat, and what it serves: a port of
//! statsd_exporter v0.26.1's `exporter.handleEvent` and `registry`, then client_golang
//! v1.19.1's `Registry.Gather` and common v0.48.0's text format, for the metrics that sink
//! registers on Go's default registry.

use super::MetricType;
use super::mapper::{Action, DEFAULT_BUCKETS, Mapper, ObserverType};
use super::summary::{Options, Summary, Written};
use crate::go::format_float as go_float;
use std::collections::{BTreeMap, HashMap};
use std::fmt::Write;

/// The series a histogram adds to its name, which other metrics must not take.
const HISTOGRAM_SUFFIXES: [&str; 3] = ["_bucket", "_count", "_sum"];

const DEFAULT_HELP: &str = "Metric autogenerated by statsd_exporter.";

/// The kind of a registered metric.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    Counter,
    Gauge,
    Histogram,
    Summary,
}

impl Kind {
    fn type_name(self) -> &'static str {
        match self {
            Kind::Counter => "counter",
            Kind::Gauge => "gauge",
            Kind::Histogram => "histogram",
            Kind::Summary => "summary",
        }
    }

    /// client_golang's wording in Gather errors.
    fn article_name(self) -> &'static str {
        match self {
            Kind::Counter => "a Counter",
            Kind::Gauge => "a Gauge",
            Kind::Histogram => "a Histogram",
            Kind::Summary => "a Summary",
        }
    }
}

/// One series' value, kept like client_golang keeps it.
#[derive(Debug, Clone)]
enum Value {
    /// A counter: whole increments and the rest apart, summed when read.
    Counter {
        whole: u64,
        fraction: f64,
    },
    Gauge(f64),
    Histogram {
        upper_bounds: Vec<f64>,
        buckets: Vec<u64>,
        sum: f64,
        count: u64,
    },
    /// A summary, and what it gave at the last Gather.
    Summary(Box<Summary>, Option<Written>),
}

/// What a summary vector's series are made with: the objectives (quantile, error) and the
/// options, client_golang's defaults applied.
#[derive(Debug, Clone)]
struct SummaryConfig {
    objectives: Vec<(f64, f64)>,
    options: Options,
}

impl SummaryConfig {
    /// statsd_exporter's quantiles and client_golang's options.
    fn default_config() -> Self {
        Self {
            objectives: vec![(0.5, 0.05), (0.9, 0.01), (0.99, 0.001)],
            options: Options {
                max_age: 600_000_000_000,
                age_buckets: 5,
                buf_cap: 500,
            },
        }
    }
}

impl Value {
    /// A new series of `kind`; a summary is made with `summary` at `wall` time.
    fn new(kind: Kind, upper_bounds: &[f64], summary: Option<&SummaryConfig>, wall: i64) -> Self {
        match kind {
            Kind::Summary => {
                let config = summary.expect("summary vectors are made with their config");
                let summary = Summary::new(&config.objectives, config.options, wall);
                Value::Summary(Box::new(summary), None)
            }
            Kind::Counter => Value::Counter {
                whole: 0,
                fraction: 0.0,
            },
            Kind::Gauge => Value::Gauge(0.0),
            Kind::Histogram => Value::Histogram {
                upper_bounds: upper_bounds.to_vec(),
                buckets: vec![0; upper_bounds.len()],
                sum: 0.0,
                count: 0,
            },
        }
    }

    /// `counter.Add` (for a value that is not negative) or `gauge.Add`.
    fn add(&mut self, v: f64) {
        match self {
            Value::Counter { whole, fraction } => {
                let w = v as u64;
                if w as f64 == v {
                    *whole = whole.wrapping_add(w);
                } else {
                    *fraction += v;
                }
            }
            Value::Gauge(value) => *value += v,
            Value::Histogram { .. } | Value::Summary(..) => {}
        }
    }

    /// A counter's value as client_golang reads it.
    fn counter_value(whole: u64, fraction: f64) -> f64 {
        fraction + whole as f64
    }

    fn set(&mut self, v: f64) {
        if let Value::Gauge(value) = self {
            *value = v;
        }
    }

    fn observe(&mut self, v: f64) {
        if let Value::Histogram {
            upper_bounds,
            buckets,
            sum,
            count,
        } = self
        {
            // `sort.SearchFloat64s`: the first bound not below v (none for NaN).
            let i = upper_bounds.partition_point(|b| {
                !matches!(
                    b.partial_cmp(&v),
                    Some(std::cmp::Ordering::Greater | std::cmp::Ordering::Equal)
                )
            });
            if i < buckets.len() {
                buckets[i] += 1;
            }
            *sum += v;
            *count += 1;
        }
    }
}

/// A metric vector registered for a name and a set of label names, with its series.
#[derive(Debug)]
struct Vector {
    name: String,
    help: String,
    kind: Kind,
    label_names: Vec<String>,
    /// `NewDesc`'s error, reported for each series at Gather.
    desc_error: Option<String>,
    upper_bounds: Vec<f64>,
    summary: Option<SummaryConfig>,
    series: BTreeMap<Vec<String>, Value>,
}

impl Vector {
    fn new(name: &str, help: &str, kind: Kind, label_names: Vec<String>) -> Self {
        let desc_error = desc_error(name, &label_names);
        Self {
            name: name.to_string(),
            help: help.to_string(),
            kind,
            label_names,
            desc_error,
            upper_bounds: Vec::new(),
            summary: None,
            series: BTreeMap::new(),
        }
    }

    /// The series with these label values, created at zero.
    fn with(&mut self, values: &[&str]) -> &mut Value {
        self.with_at(values, 0)
    }

    /// The series with these label values, created at zero, a summary at `wall` time.
    fn with_at(&mut self, values: &[&str], wall: i64) -> &mut Value {
        let (kind, bounds, summary) = (self.kind, &self.upper_bounds, &self.summary);
        self.series
            .entry(values.iter().map(|v| v.to_string()).collect())
            .or_insert_with(|| Value::new(kind, bounds, summary.as_ref(), wall))
    }
}

/// `NewDesc`'s checks of a metric name and its label names.
fn desc_error(name: &str, label_names: &[String]) -> Option<String> {
    if !is_valid_metric_name(name) {
        return Some(format!(
            "{} is not a valid metric name",
            crate::go::quote(name)
        ));
    }
    label_names
        .iter()
        .find(|l| !is_valid_label_name(l))
        .map(|l| {
            format!(
                "{} is not a valid label name for metric {}",
                crate::go::quote(l),
                crate::go::quote(name)
            )
        })
}

fn is_valid_metric_name(name: &str) -> bool {
    !name.is_empty()
        && name.char_indices().all(|(i, c)| {
            c.is_ascii_alphabetic() || c == '_' || c == ':' || (i > 0 && c.is_ascii_digit())
        })
}

/// `checkLabelName`: a valid label name not reserved with `__`.
fn is_valid_label_name(name: &str) -> bool {
    !name.is_empty()
        && !name.starts_with("__")
        && name
            .char_indices()
            .all(|(i, c)| c.is_ascii_alphabetic() || c == '_' || (i > 0 && c.is_ascii_digit()))
}

/// A series registered by the exporter: when it was last updated, for how long it lives.
#[derive(Debug)]
struct Registered {
    last_registered_at: i64,
    ttl: i64,
    vector: usize,
    values: Vec<String>,
}

/// statsd_exporter's `metrics.Metric`: the vectors and series under one name.
#[derive(Debug)]
struct Metric {
    kind: Kind,
    /// Label names → vector index.
    vectors: HashMap<Vec<String>, usize>,
    /// (label names, label values) → series.
    series: HashMap<(Vec<String>, Vec<String>), Registered>,
}

/// The statsd_exporter self-metrics upstream's sink registers, in the default registry.
const EVENTS_ACTIONS: usize = 0;
const EVENTS_UNMAPPED: usize = 1;
const METRICS_COUNT: usize = 2;
const EVENTS_CONFLICT: usize = 3;
const EVENTS: usize = 4;
const EVENTS_ERROR: usize = 5;
const REQUESTS: usize = 6;
const IN_FLIGHT: usize = 7;

fn fixed_vectors() -> Vec<Vector> {
    let vector = |name: &str, help: &str, kind, label: Option<&str>| {
        Vector::new(
            name,
            help,
            kind,
            label.into_iter().map(String::from).collect(),
        )
    };
    let mut vectors = vec![
        vector(
            "statsd_exporter_events_actions_total",
            "The total number of StatsD events by action.",
            Kind::Counter,
            Some("action"),
        ),
        vector(
            "statsd_exporter_events_unmapped_total",
            "The total number of StatsD events no mapping was found for.",
            Kind::Counter,
            None,
        ),
        vector(
            "statsd_exporter_metrics_total",
            "The total number of metrics.",
            Kind::Gauge,
            Some("type"),
        ),
        vector(
            "statsd_exporter_events_conflict_total",
            "The total number of StatsD events with conflicting names.",
            Kind::Counter,
            Some("type"),
        ),
        vector(
            "statsd_exporter_events_total",
            "The total number of StatsD events seen.",
            Kind::Counter,
            Some("type"),
        ),
        vector(
            "statsd_exporter_events_error_total",
            "The total number of StatsD events discarded due to errors.",
            Kind::Counter,
            Some("reason"),
        ),
        vector(
            "promhttp_metric_handler_requests_total",
            "Total number of scrapes by HTTP status code.",
            Kind::Counter,
            Some("code"),
        ),
        vector(
            "promhttp_metric_handler_requests_in_flight",
            "Current number of scrapes being served.",
            Kind::Gauge,
            None,
        ),
    ];
    // A plain counter or gauge always has its one series; promhttp initialises three codes.
    vectors[EVENTS_UNMAPPED].with(&[]);
    vectors[IN_FLIGHT].with(&[]);
    for code in ["200", "500", "503"] {
        vectors[REQUESTS].with(&[code]);
    }
    vectors
}

/// A flushed stat.
#[derive(Debug, Clone, Copy)]
pub(super) enum Event {
    Counter(f64),
    Gauge(f64),
    Observer(f64),
}

impl Event {
    fn metric_type(self) -> MetricType {
        match self {
            Event::Counter(_) => MetricType::Counter,
            Event::Gauge(_) => MetricType::Gauge,
            Event::Observer(_) => MetricType::Observer,
        }
    }

    fn value(self) -> f64 {
        match self {
            Event::Counter(v) | Event::Gauge(v) | Event::Observer(v) => v,
        }
    }
}

/// The exporter and the default registry it fills.
#[derive(Debug)]
pub(super) struct Exporter {
    mapper: Mapper,
    /// The self-metrics, then the exporter's vectors in creation order.
    vectors: Vec<Vector>,
    metrics: HashMap<String, Metric>,
}

/// Go's `time.Now` as summaries compare it (monotonically; statsd_exporter's clock is for
/// TTLs only), in nanoseconds since the first reading.
fn monotonic_nanos() -> i64 {
    static START: std::sync::OnceLock<std::time::Instant> = std::sync::OnceLock::new();
    START
        .get_or_init(std::time::Instant::now)
        .elapsed()
        .as_nanos() as i64
}

impl Exporter {
    pub fn new(mapper: Mapper) -> Self {
        Self {
            mapper,
            vectors: fixed_vectors(),
            metrics: HashMap::new(),
        }
    }

    fn inc(&mut self, vector: usize, label: &[&str]) {
        self.vectors[vector].with(label).add(1.0);
    }

    /// `handleEvent`, at `now` (nanoseconds).
    pub fn handle(&mut self, name: &str, event: Event, now: i64) {
        let mapped = self.mapper.get_mapping(name, event.metric_type());
        if mapped.as_ref().is_some_and(|m| m.action == Action::Drop) {
            self.inc(EVENTS_ACTIONS, &["drop"]);
            return;
        }
        let help = match mapped.as_ref().map(|m| m.help.as_str()) {
            Some(help) if !help.is_empty() => help.to_string(),
            _ => DEFAULT_HELP.to_string(),
        };
        let (metric_name, labels) = match &mapped {
            Some(mapped) => {
                if mapped.name.is_empty() {
                    self.inc(EVENTS_ERROR, &["empty_metric_name"]);
                    return;
                }
                self.inc(EVENTS_ACTIONS, &["map"]);
                (escape_metric_name(&mapped.name), mapped.labels.clone())
            }
            None => {
                self.inc(EVENTS_UNMAPPED, &[]);
                (escape_metric_name(name), BTreeMap::new())
            }
        };
        let ttl = match &mapped {
            Some(mapped) => mapped.ttl,
            None => self.mapper.default_ttl(),
        };
        let mut value = event.value();
        if let Some(scale) = mapped.as_ref().and_then(|m| m.scale) {
            value *= scale;
        }
        let series = Series {
            name: &metric_name,
            labels: &labels,
            help: &help,
            ttl,
            now,
        };
        match event {
            Event::Counter(_) => {
                if value < 0.0 {
                    self.inc(EVENTS_ERROR, &["illegal_negative_counter"]);
                    return;
                }
                match self.get(&series, Kind::Counter, &[]) {
                    Some(v) => {
                        v.add(value);
                        self.inc(EVENTS, &["counter"]);
                    }
                    None => self.inc(EVENTS_CONFLICT, &["counter"]),
                }
            }
            Event::Gauge(_) => match self.get(&series, Kind::Gauge, &[]) {
                Some(v) => {
                    v.set(value);
                    self.inc(EVENTS, &["gauge"]);
                }
                None => self.inc(EVENTS_CONFLICT, &["gauge"]),
            },
            Event::Observer(_) => {
                let observer = mapped
                    .as_ref()
                    .and_then(|m| m.observer_type)
                    .or(self.mapper.default_observer_type());
                match observer {
                    Some(ObserverType::Histogram) => {
                        let buckets = histogram_buckets(&self.mapper, mapped.as_ref());
                        match self.get(&series, Kind::Histogram, &buckets) {
                            Some(v) => {
                                v.observe(value);
                                self.inc(EVENTS, &["observer"]);
                            }
                            None => self.inc(EVENTS_CONFLICT, &["observer"]),
                        }
                    }
                    Some(ObserverType::Summary) | None => {
                        let config = summary_config(&self.mapper, mapped.as_ref());
                        let wall = monotonic_nanos();
                        match self.get_summary(&series, config, wall) {
                            Some(Value::Summary(summary, _)) => {
                                summary.observe(value, wall);
                                self.inc(EVENTS, &["observer"]);
                            }
                            _ => self.inc(EVENTS_CONFLICT, &["observer"]),
                        }
                    }
                }
            }
        }
    }

    /// `MetricConflicts`: `name` is registered with another kind.
    fn conflicts(&self, name: &str, kind: Kind) -> bool {
        self.metrics.get(name).is_some_and(|m| m.kind != kind)
    }

    /// `GetSummary`: the series, a new vector made with `config` (`None` when client_golang
    /// would panic or hang: see `summary_config`, or a `quantile` label), or `None` on a name
    /// conflict.
    fn get_summary(
        &mut self,
        s: &Series,
        config: Option<SummaryConfig>,
        wall: i64,
    ) -> Option<&mut Value> {
        let config = config.filter(|_| !s.labels.contains_key("quantile"));
        self.register(s, Kind::Summary, &[], config, wall)
    }

    /// `GetCounter`, `GetGauge` and `GetHistogram`: the series, registering its vector and
    /// itself as needed, or `None` on a name conflict.
    fn get(&mut self, s: &Series, kind: Kind, upper_bounds: &[f64]) -> Option<&mut Value> {
        self.register(s, kind, upper_bounds, None, 0)
    }

    /// The series of `kind`, registered as needed; a summary's needs its `config`.
    fn register(
        &mut self,
        s: &Series,
        kind: Kind,
        upper_bounds: &[f64],
        summary: Option<SummaryConfig>,
        wall: i64,
    ) -> Option<&mut Value> {
        let names: Vec<String> = s.labels.keys().cloned().collect();
        let values: Vec<String> = s.labels.values().cloned().collect();
        let key = (names.clone(), values.clone());
        let existing = self
            .metrics
            .get_mut(s.name)
            .filter(|m| m.kind == kind)
            .and_then(|metric| {
                let series = metric.series.get_mut(&key);
                let found = series.is_some();
                if let Some(series) = series {
                    series.last_registered_at = s.now;
                }
                metric.vectors.get(&names).map(|v| (*v, found))
            });
        if let Some((vector, true)) = existing {
            let values: Vec<&str> = values.iter().map(String::as_str).collect();
            return Some(self.vectors[vector].with_at(&values, wall));
        }
        let name = s.name;
        let conflict = match kind {
            Kind::Histogram => {
                self.conflicts(name, kind)
                    || HISTOGRAM_SUFFIXES
                        .iter()
                        .any(|suffix| self.conflicts(&format!("{name}{suffix}"), kind))
            }
            Kind::Summary => {
                self.conflicts(name, kind)
                    || ["_sum", "_count"]
                        .iter()
                        .any(|suffix| self.conflicts(&format!("{name}{suffix}"), kind))
                    // A new vector client_golang cannot make (docs/parity.md §7); an existing
                    // one keeps its own options.
                    || (existing.is_none() && summary.is_none())
            }
            _ => {
                self.conflicts(name, kind)
                    || HISTOGRAM_SUFFIXES.iter().any(|suffix| {
                        name.strip_suffix(suffix)
                            .is_some_and(|base| self.conflicts(base, Kind::Counter))
                    })
            }
        };
        // client_golang panics on these when creating the series, which stops upstream's
        // process; here the event is counted as a conflict (docs/parity.md §7).
        let invalid_histogram = kind == Kind::Histogram
            && (names.iter().any(|n| n == "le") || upper_bounds.windows(2).any(|w| w[0] >= w[1]));
        if conflict || invalid_histogram {
            return None;
        }
        let vector = match existing {
            Some((vector, _)) => vector,
            None => {
                self.inc(METRICS_COUNT, &[kind.type_name()]);
                let mut vector = Vector::new(name, s.help, kind, names.clone());
                vector.upper_bounds = upper_bounds.to_vec();
                vector.summary = summary;
                self.vectors.push(vector);
                self.vectors.len() - 1
            }
        };
        let metric = self
            .metrics
            .entry(name.to_string())
            .or_insert_with(|| Metric {
                kind,
                vectors: HashMap::new(),
                series: HashMap::new(),
            });
        metric.vectors.entry(names).or_insert(vector);
        match metric.series.get_mut(&key) {
            Some(series) => {
                series.last_registered_at = s.now;
                series.ttl = s.ttl;
            }
            None => {
                metric.series.insert(
                    key,
                    Registered {
                        last_registered_at: s.now,
                        ttl: s.ttl,
                        vector,
                        values: values.clone(),
                    },
                );
            }
        }
        let values: Vec<&str> = values.iter().map(String::as_str).collect();
        Some(self.vectors[vector].with_at(&values, wall))
    }

    /// `RemoveStaleMetrics`: deletes the series not updated for longer than their TTL. Their
    /// vectors stay, and so do their names' kinds.
    pub fn remove_stale_metrics(&mut self, now: i64) {
        for metric in self.metrics.values_mut() {
            metric.series.retain(|_, series| {
                let stale =
                    series.ttl != 0 && series.last_registered_at.saturating_add(series.ttl) < now;
                if stale {
                    self.vectors[series.vector].series.remove(&series.values);
                }
                !stale
            });
        }
    }

    /// A scrape, as promhttp serves it: the in-flight gauge shows the scrapes being served
    /// (this one included) while gathering, and the scrape is counted by its status.
    pub fn scrape(&mut self, in_flight: u64) -> Result<String, String> {
        self.vectors[IN_FLIGHT].with(&[]).set(in_flight as f64);
        let gathered = self.gather();
        self.vectors[IN_FLIGHT]
            .with(&[])
            .set(in_flight.saturating_sub(1) as f64);
        let code = if gathered.is_ok() { "200" } else { "500" };
        self.vectors[REQUESTS].with(&[code]).add(1.0);
        gathered
    }

    /// `Registry.Gather` and the text format, or Gather's errors.
    fn gather(&mut self) -> Result<String, String> {
        // Each summary's `Write`, which flushes its buffers.
        let wall = monotonic_nanos();
        for vector in &mut self.vectors {
            for value in vector.series.values_mut() {
                if let Value::Summary(summary, written) = value {
                    *written = Some(summary.write(wall));
                }
            }
        }
        let mut families: BTreeMap<&str, Family> = BTreeMap::new();
        let mut errors = Vec::new();
        let mut seen = std::collections::HashSet::new();
        for vector in &self.vectors {
            for (values, value) in &vector.series {
                if let Some(error) = &vector.desc_error {
                    errors.push(error.clone());
                    continue;
                }
                let mut labels: Vec<(&str, &str)> = vector
                    .label_names
                    .iter()
                    .map(String::as_str)
                    .zip(values.iter().map(String::as_str))
                    .collect();
                labels.sort();
                let sample = Sample { labels, value };
                let family = match families.get_mut(vector.name.as_str()) {
                    Some(family) => {
                        if family.help != vector.help {
                            errors.push(format!(
                                "collected metric {} {} has help {} but should have {}",
                                vector.name,
                                sample.dto(),
                                crate::go::quote(&vector.help),
                                crate::go::quote(family.help)
                            ));
                            continue;
                        }
                        if family.kind != vector.kind {
                            errors.push(format!(
                                "collected metric {} {} should be {}",
                                vector.name,
                                sample.dto(),
                                family.kind.article_name()
                            ));
                            continue;
                        }
                        family
                    }
                    None => {
                        if let Err(error) = suffix_collision(&vector.name, vector.kind, &families) {
                            errors.push(error);
                            continue;
                        }
                        families.entry(&vector.name).or_insert(Family {
                            help: &vector.help,
                            kind: vector.kind,
                            samples: Vec::new(),
                        })
                    }
                };
                let identity: Vec<(String, String)> = sample
                    .labels
                    .iter()
                    .map(|(k, v)| (k.to_string(), v.to_string()))
                    .collect();
                if !seen.insert((vector.name.clone(), identity)) {
                    errors.push(format!(
                        "collected metric {} {{ {}}} was collected before with the same name and label values",
                        crate::go::quote(&vector.name),
                        sample.dto()
                    ));
                    continue;
                }
                family.samples.push(sample);
            }
        }
        match errors.len() {
            0 => {}
            1 => return Err(errors.remove(0)),
            n => {
                let mut text = format!("{n} error(s) occurred:");
                for error in errors {
                    text += &format!("\n* {error}");
                }
                return Err(text);
            }
        }
        let mut out = String::new();
        for (name, family) in &mut families {
            // `MetricSorter`: by label count, then label values in order.
            family.samples.sort_by(|a, b| {
                a.labels.len().cmp(&b.labels.len()).then_with(|| {
                    let values = a.labels.iter().map(|(_, v)| v);
                    values
                        .cmp(b.labels.iter().map(|(_, v)| v))
                        .then_with(|| a.labels.cmp(&b.labels))
                })
            });
            family.write(name, &mut out);
        }
        Ok(out)
    }
}

/// The inputs of `get` that describe a series.
struct Series<'a> {
    name: &'a str,
    labels: &'a BTreeMap<String, String>,
    help: &'a str,
    ttl: i64,
    now: i64,
}

/// The classic buckets of a new histogram: the mapping's, else the defaults; client_golang
/// falls back to `DefBuckets` when there are none (a mapper that failed to load).
fn histogram_buckets(mapper: &Mapper, mapped: Option<&super::mapper::Mapped>) -> Vec<f64> {
    let buckets = mapped
        .and_then(|m| m.histogram_options.as_ref())
        .and_then(|h| h.buckets.clone())
        .filter(|b| !b.is_empty())
        .or_else(|| mapper.default_buckets())
        .unwrap_or_default();
    let mut buckets = if buckets.is_empty() && mapper.native_histogram_bucket_factor() <= 1.0 {
        DEFAULT_BUCKETS.to_vec()
    } else {
        buckets
    };
    // The +Inf bucket is implicit.
    if buckets.last().is_some_and(|b| *b == f64::INFINITY) {
        buckets.pop();
    }
    buckets
}

struct Family<'a> {
    help: &'a str,
    kind: Kind,
    samples: Vec<Sample<'a>>,
}

struct Sample<'a> {
    labels: Vec<(&'a str, &'a str)>,
    value: &'a Value,
}

impl Sample<'_> {
    /// The `dto.Metric` as Go's `%s` prints it in Gather errors (with single spaces).
    fn dto(&self) -> String {
        let mut out: Vec<String> = self
            .labels
            .iter()
            .map(|(k, v)| {
                format!(
                    "label:{{name:{} value:{}}}",
                    crate::go::quote(k),
                    crate::go::quote(v)
                )
            })
            .collect();
        let value = match self.value {
            Value::Counter { whole, fraction } => {
                format!(
                    "counter:{{value:{}}}",
                    proto_float(Value::counter_value(*whole, *fraction))
                )
            }
            Value::Gauge(v) => format!("gauge:{{value:{}}}", proto_float(*v)),
            Value::Histogram { count, sum, .. } => format!(
                "histogram:{{sample_count:{count} sample_sum:{}}}",
                proto_float(*sum)
            ),
            Value::Summary(_, written) => {
                let written = written.as_ref().expect("written at Gather");
                let quantiles: String = written
                    .quantiles
                    .iter()
                    .map(|(q, v)| {
                        format!(
                            " quantile:{{quantile:{} value:{}}}",
                            proto_float(*q),
                            proto_float(*v)
                        )
                    })
                    .collect();
                format!(
                    "summary:{{sample_count:{} sample_sum:{}{quantiles}}}",
                    written.count,
                    proto_float(written.sum)
                )
            }
        };
        out.push(value);
        out.join(" ")
    }
}

impl Family<'_> {
    fn write(&self, name: &str, out: &mut String) {
        let help = self.help.replace('\\', "\\\\").replace('\n', "\\n");
        let _ = writeln!(out, "# HELP {name} {help}");
        let _ = writeln!(out, "# TYPE {name} {}", self.kind.type_name());
        for sample in &self.samples {
            match sample.value {
                Value::Counter { whole, fraction } => {
                    write_sample(
                        out,
                        name,
                        "",
                        &sample.labels,
                        None,
                        *fraction + *whole as f64,
                    );
                }
                Value::Summary(_, written) => {
                    let written = written.as_ref().expect("written at Gather");
                    for (q, v) in &written.quantiles {
                        let quantile = Some(("quantile", *q));
                        write_sample(out, name, "", &sample.labels, quantile, *v);
                    }
                    write_sample(out, name, "_sum", &sample.labels, None, written.sum);
                    let count = written.count as f64;
                    write_sample(out, name, "_count", &sample.labels, None, count);
                }
                Value::Gauge(v) => write_sample(out, name, "", &sample.labels, None, *v),
                Value::Histogram {
                    upper_bounds,
                    buckets,
                    sum,
                    count,
                } => {
                    let mut cumulative = 0;
                    for (bound, n) in upper_bounds.iter().zip(buckets) {
                        cumulative += n;
                        write_sample(
                            out,
                            name,
                            "_bucket",
                            &sample.labels,
                            Some(("le", *bound)),
                            cumulative as f64,
                        );
                    }
                    let inf = Some(("le", f64::INFINITY));
                    write_sample(out, name, "_bucket", &sample.labels, inf, *count as f64);
                    write_sample(out, name, "_sum", &sample.labels, None, *sum);
                    write_sample(out, name, "_count", &sample.labels, None, *count as f64);
                }
            }
        }
    }
}

fn write_sample(
    out: &mut String,
    name: &str,
    suffix: &str,
    labels: &[(&str, &str)],
    extra: Option<(&str, f64)>,
    value: f64,
) {
    out.push_str(name);
    out.push_str(suffix);
    let mut separator = '{';
    for (label, label_value) in labels {
        let escaped = label_value
            .replace('\\', "\\\\")
            .replace('\n', "\\n")
            .replace('"', "\\\"");
        let _ = write!(out, "{separator}{label}=\"{escaped}\"");
        separator = ',';
    }
    if let Some((label, value)) = extra {
        let _ = write!(out, "{separator}{label}=\"{}\"", text_float(value));
        separator = ',';
    }
    if separator == ',' {
        out.push('}');
    }
    let _ = writeln!(out, " {}", text_float(value));
}

/// expfmt's `writeFloat`: a zero of either sign is `0`.
fn text_float(value: f64) -> String {
    match value {
        0.0 => "0".into(),
        value => go_float(value),
    }
}

/// A float in Go's prototext, as Gather errors print a metric: `nan`, `inf`, `-inf`.
fn proto_float(value: f64) -> String {
    match value {
        v if v.is_nan() => "nan".into(),
        f64::INFINITY => "inf".into(),
        f64::NEG_INFINITY => "-inf".into(),
        v => go_float(v),
    }
}

/// `checkSuffixCollisions`, for a new family.
fn suffix_collision(
    name: &str,
    kind: Kind,
    families: &BTreeMap<&str, Family>,
) -> Result<(), String> {
    let base = HISTOGRAM_SUFFIXES
        .iter()
        .find_map(|suffix| name.strip_suffix(suffix));
    if let Some(base) = base {
        let other = families.get(base).map(|f| f.kind);
        let collides = match other {
            Some(Kind::Summary) => !name.ends_with("_bucket"),
            Some(Kind::Histogram) => true,
            _ => false,
        };
        if let Some(kind) = other.filter(|_| collides) {
            return Err(format!(
                "collected metric named {} collides with previously collected {} named {}",
                crate::go::quote(name),
                kind.type_name(),
                crate::go::quote(base)
            ));
        }
    }
    if matches!(kind, Kind::Summary | Kind::Histogram) {
        for suffix in ["_count", "_sum"] {
            let other = format!("{name}{suffix}");
            if families.contains_key(other.as_str()) {
                return Err(format!(
                    "collected histogram or summary named {} collides with previously collected metric named {}",
                    crate::go::quote(name),
                    crate::go::quote(&other)
                ));
            }
        }
    }
    let bucket = format!("{name}_bucket");
    if kind == Kind::Histogram && families.contains_key(bucket.as_str()) {
        return Err(format!(
            "collected histogram named {} collides with previously collected metric named {}",
            crate::go::quote(name),
            crate::go::quote(&bucket)
        ));
    }
    Ok(())
}

/// `GetSummary`'s objectives and options: the mapping's quantiles if it has some, else the
/// defaults' (else 0.5, 0.9 and 0.99); the mapping's options in full if it has any, else the
/// defaults'; then client_golang's defaults for what is 0. `None` for a negative `MaxAge`
/// (client_golang panics) or one shorter than a nanosecond per age bucket (its summary would
/// loop forever on its first expired buffer).
fn summary_config(
    mapper: &Mapper,
    mapped: Option<&super::mapper::Mapped>,
) -> Option<SummaryConfig> {
    let defaults = mapper.default_summary_options();
    let mapping = mapped.and_then(|m| m.summary_options.as_ref());
    let quantiles = mapping
        .and_then(|o| o.quantiles.as_ref())
        .filter(|q| !q.is_empty())
        .or(defaults.quantiles.as_ref());
    let options = mapping.unwrap_or(defaults);
    // A Go map: a quantile given twice keeps its last error.
    let mut objectives: Vec<(f64, f64)> = Vec::new();
    for objective in quantiles.into_iter().flatten() {
        match objectives
            .iter_mut()
            .find(|(q, _)| *q == objective.quantile)
        {
            Some(existing) => existing.1 = objective.error,
            None => objectives.push((objective.quantile, objective.error)),
        }
    }
    let fallback = SummaryConfig::default_config();
    if objectives.is_empty() {
        objectives = fallback.objectives;
    }
    if options.max_age < 0 {
        return None;
    }
    let or_default = |value: i64, default: i64| if value == 0 { default } else { value };
    let options = Options {
        max_age: or_default(options.max_age, fallback.options.max_age),
        age_buckets: or_default(
            options.age_buckets.into(),
            fallback.options.age_buckets.into(),
        ) as u32,
        buf_cap: or_default(options.buf_cap.into(), fallback.options.buf_cap.into()) as u32,
    };
    if options.max_age / options.age_buckets as i64 == 0 {
        return None;
    }
    Some(SummaryConfig {
        objectives,
        options,
    })
}

/// statsd_exporter's `EscapeMetricName`: a leading digit gets a `_` before it, and each
/// character outside `[A-Za-z0-9_]` becomes `_`, except a `-` right after a `-`, which is
/// dropped.
pub(super) fn escape_metric_name(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 1);
    if name.starts_with(|c: char| c.is_ascii_digit()) {
        out.push('_');
    }
    let mut previous = None;
    for c in name.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            out.push(c);
        } else if c == '-' && previous == Some('-') {
            continue;
        } else {
            out.push('_');
        }
        previous = Some(c);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The quota lookup's counter the shipped mapper leaves alone gets the exporter's name
    /// (ADR 0003).
    #[test]
    fn unmapped_quota_lookup_counters_are_escaped() {
        assert_eq!(
            escape_metric_name("ratelimit.quota_lookup.total_requests"),
            "ratelimit_quota_lookup_total_requests"
        );
    }

    /// `GetSummary`: a mapping's options replace the defaults' in full, then client_golang's
    /// defaults fill what is 0; its quantiles only when it has some.
    #[test]
    fn a_mapping_s_summary_options_replace_the_defaults() {
        let mapper = Mapper::from_yaml(
            "
defaults:
  summary_options: {max_age: 1h, buf_cap: 7, quantiles: [{quantile: 0.3, error: 0.03}]}
mappings:
- match: a.*
  name: a
  summary_options: {max_age: 1m, age_buckets: 2}
",
        )
        .unwrap();
        let mapped = mapper.get_mapping("a.x", super::super::MetricType::Observer);
        let config = summary_config(&mapper, mapped.as_ref()).unwrap();
        assert_eq!(config.objectives, vec![(0.3, 0.03)]);
        let options = (
            config.options.max_age,
            config.options.age_buckets,
            config.options.buf_cap,
        );
        assert_eq!(options, (60_000_000_000, 2, 500));
        let config = summary_config(&mapper, None).unwrap();
        let options = (
            config.options.max_age,
            config.options.age_buckets,
            config.options.buf_cap,
        );
        assert_eq!(options, (3_600_000_000_000, 5, 7));
    }

    /// Options client_golang cannot use make no summary: a negative `MaxAge` (it panics), or
    /// one under a nanosecond per age bucket (it loops forever).
    #[test]
    fn unusable_summary_options_make_no_summary() {
        for options in ["{max_age: -1s}", "{max_age: 4ns, age_buckets: 5}"] {
            let yaml = format!("mappings:\n- {{match: a.*, name: a, summary_options: {options}}}");
            let mapper = Mapper::from_yaml(&yaml).unwrap();
            let mapped = mapper.get_mapping("a.x", super::super::MetricType::Observer);
            assert!(
                summary_config(&mapper, mapped.as_ref()).is_none(),
                "{options}"
            );
        }
    }

    /// Gather errors print floats as Go's prototext; the text format prints any zero as `0`.
    #[test]
    fn floats_are_printed_like_go() {
        let printed: Vec<String> = [f64::NAN, f64::INFINITY, f64::NEG_INFINITY, -0.0, 1.5]
            .map(proto_float)
            .into();
        assert_eq!(printed, ["nan", "inf", "-inf", "-0", "1.5"]);
        assert_eq!(
            (text_float(-0.0), text_float(f64::NAN)),
            ("0".into(), "NaN".into())
        );
    }
}
